def test_unsupported_contract_version_raises():
    contract = _contract()
    # contract_version is validated by the Literal type at parse time, so
    # simulate an old/unsupported version by monkeypatching the compiler's
    # supported set instead of trying to construct an invalid contract.
    import app.services.script_compiler.compiler as compiler_module
    original = compiler_module.SUPPORTED_CONTRACT_VERSIONS
    compiler_module.SUPPORTED_CONTRACT_VERSIONS = frozenset()
    try:
        with pytest.raises(UnsupportedContractVersionError):
            compile_contract(contract)
    finally:
        compiler_module.SUPPORTED_CONTRACT_VERSIONS = original
