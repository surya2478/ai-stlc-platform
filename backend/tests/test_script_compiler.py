import pytest

from app.agents.automation.generation_contract import AutomationGenerationContract
from app.services.script_compiler import compile_contract
from app.services.script_compiler.compiler import UnsupportedContractVersionError

LOGIN_CONTRACT = {
    "contractVersion": "1.0",
    "testCaseId": "TC-0001",
    "requirementId": "REQ-0001",
    "scriptType": "playwright-typescript",
    "environmentProfile": "QA",
    "businessFlow": "Valid login succeeds",
    "testDataBindings": [{"name": "username", "placeholder": "${username}", "fallback": "demo"}],
    "pageObjects": [{
        "name": "LoginPage",
        "route": "/login",
        "elements": [
            {"name": "usernameInput", "locatorStrategy": "label", "locatorValue": "Username"},
            {"name": "submitButton", "locatorStrategy": "role", "locatorValue": "Sign in", "roleHint": "button"},
        ],
    }],
    "steps": [
        {"phase": "arrange", "action": "navigate", "value": "/login"},
        {"phase": "act", "action": "fill", "target": "LoginPage.usernameInput", "dataBinding": "username"},
        {"phase": "act", "action": "click", "target": "LoginPage.submitButton"},
    ],
    "assertions": [{"type": "url", "target": "page", "expected": "dashboard"}],
    "evidenceRequired": ["logged-in-user"],
    "cleanupActions": [{"type": "ui_action", "description": "session ends with browser context"}],
}


def _contract(**overrides) -> AutomationGenerationContract:
    data = dict(LOGIN_CONTRACT)
    data.update(overrides)
    return AutomationGenerationContract.model_validate(data)


def test_compile_playwright_produces_expected_file_tree():
    bundle = compile_contract(_contract())
    assert bundle.entry_path.startswith("specs/")
    assert bundle.entry_path.endswith(".spec.ts")
    assert "pages/LoginPage.ts" in bundle.files
    assert "fixtures/testData.fixture.ts" in bundle.files
    assert "utils/evidenceHelper.ts" in bundle.files
    # No API/DB validations declared -> those utils are not pulled in.
    assert "utils/apiClient.ts" not in bundle.files
    assert "utils/dbValidator.ts" not in bundle.files


def test_compile_playwright_spec_has_generation_header_and_structure():
    bundle = compile_contract(_contract())
    spec = bundle.files[bundle.entry_path]
    assert "GENERATED BY nxtQA Script Compiler" in spec
    assert "Test Case: TC-0001" in spec
    assert "Requirement: REQ-0001" in spec
    assert "// Arrange" in spec
    assert "// Act" in spec
    assert "// Assert" in spec
    assert "// Evidence" in spec
    assert "// Cleanup" in spec
    assert "loginPage.usernameInput.fill(TEST_DATA.username)" in spec
    assert "await expect(page).toHaveURL(new RegExp('dashboard'));" in spec


def test_url_assertion_with_slashes_does_not_break_regex_syntax():
    # A live run failed with invalid JS: `/https://mail.google.com//` — the
    # "//" from the URL's own scheme prematurely closed the bare regex
    # literal delimiter. new RegExp('...') has no delimiter to collide with.
    contract = _contract(assertions=[
        {"type": "url", "target": "page", "expected": "https://mail.google.com/"},
    ])
    bundle = compile_contract(contract)
    spec = bundle.files[bundle.entry_path]
    assert "await expect(page).toHaveURL(new RegExp('https://mail.google.com/'));" in spec
    assert "toHaveURL(/https://mail.google.com//)" not in spec


def test_wait_for_url_step_with_slashes_does_not_break_regex_syntax():
    contract = _contract(steps=[
        {"phase": "arrange", "action": "navigate", "value": "/login"},
        {"phase": "assert", "action": "wait_for_url", "value": "https://mail.google.com/"},
    ])
    bundle = compile_contract(contract)
    spec = bundle.files[bundle.entry_path]
    assert "await page.waitForURL(new RegExp('https://mail.google.com/'));" in spec


def test_compile_is_deterministic_for_identical_contracts():
    bundle_a = compile_contract(_contract())
